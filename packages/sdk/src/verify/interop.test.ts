import { describe, it, expect } from 'vitest'
import { readFileSync, existsSync } from 'node:fs'
import { canonicalize, digest } from './canonical.js'
import { verifyEnvelope, fromBase64 } from './envelope.js'
import { readPublication, matchesPin } from './publication.js'

/**
 * Agreement with the signer, checked against the corpus rather than against the signer's code.
 *
 * `conformance/vectors.json` records, for each vector, the payload, its canonical string and its
 * digest — produced by the CMS. This file re-derives both from **this** implementation and compares.
 * Nothing is imported from the CMS, which is the only reason the comparison means anything.
 *
 * The specification is explicit about how to read a disagreement: it *"localises an ambiguity in
 * this document, which is the artefact under evaluation — not the implementations."* So a failure
 * here is a finding about the specification first, and about this code second.
 *
 * The envelope vectors and their verdicts are step 19's business. What this file covers is
 * canonicalization, and the **component publication** — one signed document carrying what a
 * component accepts and, when it has any, the code that implements it.
 *
 * The component vectors are here because they are the ones a second-language implementer is most
 * likely to get subtly wrong. A verifier that checked only the executable would accept a rewritten
 * parameter list; one that verified both envelopes without comparing them to each other would accept
 * a header and a bundle from different publications. Both failures leave every signature valid.
 */

interface CanonicalVector {
  name: string
  why: string
  payload: unknown
  canonical: string
  digest: string
}

const hex = (bytes: Uint8Array): string =>
  [...bytes].map(byte => byte.toString(16).padStart(2, '0')).join('')

/**
 * Where the corpus is, if it is anywhere.
 *
 * Named by an environment variable rather than by a path. The corpus is generated by
 * `packages/core/scripts/generate-conformance.ts` and published alongside the specification, which
 * is **not this repository** — so a hard-coded path would work on exactly one machine and would ship
 * inside a package that other people install.
 *
 * Absent, these are skipped. Step 19 makes the corpus a first-class input rather than an optional
 * one; until then this runs wherever it is pointed at something.
 */
const CORPUS = process.env.GENOACMS_CONFORMANCE_CORPUS ?? ''

interface DocumentVector {
  name: string
  why: string
  expectedType: string
  envelope: { alg: string, keyId: string, type: string, payload: unknown, signature: string }
  accept: boolean
}

/**
 * A publication's shape, checked after its signature.
 *
 * Signature-free on purpose. Each payload is properly signed in practice; what these describe is
 * what a verifier must refuse once the signature checks out.
 *
 * **These replaced the corpus's `binding` section.** A publication used to be two signed documents,
 * and the two hazards below were expressible as a *mismatched pair* — code beside a description that
 * published none, a description whose code was never fetched. Merging the documents makes them one
 * payload's shape, so they are checked by the reader rather than by a comparison between fetches.
 */
interface ShapeVector {
  name: string
  why: string
  payload: { type: string, executables?: Array<{ platform: string }> }
  accept: boolean
}

/**
 * What the page claimed about a node, against what the publication says under its own signature.
 *
 * Signature-free like `BindingVector`, and for the same reason — but a different pair. Binding
 * compares the two documents of one publication with each other; this compares the **page tree**
 * with the header, two documents signed by different acts at different times.
 */
interface PinVector {
  name: string
  why: string
  pin: { uid: string, publicationId: string, type: string }
  publication: { uid: string, publicationId: string, type: string }
  accept: boolean
}

/**
 * The corpus as this implementation reads it.
 *
 * **Every section is optional.** The corpus is an external file located by an environment variable
 * and generated by the other implementation, so one produced before a section existed is an older
 * corpus rather than a broken one — the suites below skip rather than fail. A missing section says
 * "not covered yet", which is the honest answer and not the same as a disagreement.
 */
interface Corpus {
  key?: { publicKey: string }
  canonicalization?: CanonicalVector[]
  documents?: DocumentVector[]
  shapes?: ShapeVector[]
  pins?: PinVector[]
}

const corpus = CORPUS !== '' && existsSync(CORPUS)
  ? JSON.parse(readFileSync(CORPUS, 'utf8')) as Corpus
  : undefined

const vectors = corpus?.canonicalization ?? []
const documents = corpus?.documents ?? []
const shapes = corpus?.shapes ?? []
const pins = corpus?.pins ?? []

describe.skipIf(vectors.length === 0)('the conformance corpus', () => {
  it('has vectors to check', () => {
    expect(vectors.length).toBeGreaterThan(0)
  })

  it.each(vectors.map(vector => [vector.name, vector] as const))(
    'canonicalizes %s as the signer did',
    (_name, vector) => {
      expect(canonicalize(vector.payload as never)).toBe(vector.canonical)
    }
  )

  it.each(vectors.map(vector => [vector.name, vector] as const))(
    'digests %s as the signer did',
    (_name, vector) => {
      expect(hex(digest(vector.payload as never))).toBe(vector.digest)
    }
  )
})

describe.skipIf(documents.length === 0)('component documents in the corpus', () => {
  const publicKey = fromBase64(corpus?.key?.publicKey ?? '')

  it.each(documents.map(vector => [vector.name, vector] as const))(
    'reaches the signer\'s verdict on %s',
    (_name, vector) => {
      // The corpus records what the *signer's* implementation answered. Disagreeing here means the
      // two implementations differ about a document, which the specification asks to be read as an
      // ambiguity in the specification first.
      const verified = verifyEnvelope(vector.envelope, vector.expectedType, publicKey)
      expect(verified.valid).toBe(vector.accept)
    }
  )

  it('reads the reference publication into something a component can be called by', () => {
    const reference = documents.find(vector => vector.name === 'component-publication')
    expect(reference).toBeDefined()

    const verified = verifyEnvelope(reference!.envelope, reference!.expectedType, publicKey)
    expect(verified.valid).toBe(true)

    // Verifying is not enough on its own: a signature attests to bytes, not to their shape, and a
    // publication without an attribute order is one whose component cannot be called correctly.
    const read = readPublication(verified.valid ? verified.payload : null as never)
    expect(read.ok).toBe(true)
    expect(read.ok && read.value.attributeOrder).toEqual(['attr-1'])
    // The half that used to be a second document, a second signature and a second fetch.
    expect(read.ok && read.value.executables?.[0].executableCode).toContain('function component')
  })
})

describe.skipIf(shapes.length === 0)('the shape of a publication', () => {
  it.each(shapes.map(vector => [vector.name, vector] as const))(
    'agrees with the signer about %s',
    (_name, vector) => {
      // Filled out around what the vector varies, because `readPublication` reads a whole payload and
      // the members it does not name are not what is under test.
      const payload = {
        uid: 'component-1',
        publicationId: 'publication-2',
        publisherId: 'user-1',
        publishedAt: 0,
        note: '',
        name: 'Hero',
        attributes: {},
        attributeOrder: [],
        ...vector.payload,
        ...(vector.payload.executables === undefined
          ? {}
          : {
              executables: vector.payload.executables.map(executable => ({
                platform: executable.platform,
                executableCode: 'export default function component () { return 1 }',
                compiledAt: 0
              }))
            })
      }

      expect(readPublication(payload as never).ok).toBe(vector.accept)
    }
  )
})

describe.skipIf(pins.length === 0)('checking a header against what a page pinned', () => {
  it.each(pins.map(vector => [vector.name, vector] as const))(
    'agrees with the signer about %s',
    (_name, vector) => {
      // The rest is filled in because `matchesPin` takes a read publication, and the members it
      // compares are the only ones the vector varies. Anything else here would be an assertion
      // about members the vector says nothing about.
      const publication = {
        ...vector.publication,
        type: vector.publication.type as 'prebuilt' | 'dynamic',
        publisherId: 'user-1',
        publishedAt: 0,
        note: '',
        name: 'Hero',
        attributes: {},
        attributeOrder: []
      }
      const pin = { ...vector.pin, type: vector.pin.type as 'prebuilt' | 'dynamic' }

      expect(matchesPin(publication, pin).ok).toBe(vector.accept)
    }
  )
})
